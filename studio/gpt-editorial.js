function shouldEdit(job) { return job.input.editEnabled === true && job.input.phase !== 'plan' && job.input.mode !== 'match'; }
function editPrompt(job, draft, basePrompt) {
 return basePrompt + '\n\n게시글 편집 단계입니다. 아래 초안을 독자에게 바로 보여줄 최종 글로 다듬으세요. 새 주제를 만들지 말고 항목 개수·순서·주제·form·persona·region·hotels·matched를 보존하세요. 각 항목의 title/body/titleAlternatives만 편집하세요. 초안의 제한조건과 사실, speculative에 담긴 미확인 문장은 원문 그대로 유지하세요. 외부 검색으로 사실을 추가하지 말고 제공 상품 근거와 초안만 사용하세요. 결과는 기존과 같은 items JSON입니다. 지정 본문 글자수를 다시 확인하세요.\n초안:\n' + JSON.stringify(draft);
}
function mergeEdited(job, draft, edited) {
 if (edited.items.length !== draft.items.length) throw new Error('편집 결과 개수가 바뀌었습니다.');
 return {items:draft.items.map((item,i)=>{
  const e=edited.items[i];
  if(JSON.stringify(e.matched)!==JSON.stringify(item.matched)) throw new Error('편집 중 매칭 상품이 바뀌었습니다.');
  if(/\*\*|^\s*#{1,6}\s|<\/?[a-z][^>]*>/im.test(e.body+'\n'+e.title)) throw new Error('편집 결과에 지원하지 않는 강조 서식이 있습니다.');
  if((item.speculative||[]).some(s=>!e.body.includes(s))) throw new Error('편집 중 미확인 문장의 추측 표기가 바뀌었습니다.');
  return {...item,title:e.title,body:e.body,titleAlternatives:e.titleAlternatives};
 })};
}
